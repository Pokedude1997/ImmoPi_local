// SCHEDULER
// ============================================================================

let recurringSchedulerInitialized = false;

function startRecurringScheduler() {
  if (recurringSchedulerInitialized) return;
  recurringSchedulerInitialized = true;

  const cron = require('node-cron');

  console.log('📅 Recurring automation scheduler starting...');
  console.log('⏰ Schedule: Every day at 1:00 AM (Europe/Berlin timezone)');

  // Run daily at 1 AM
  cron.schedule(
    '0 1 * * *',
    async () => {
      console.log('\n🔄 Running recurring payment automation...');
      try {
        const result = await runRecurringAutomation();
        console.log(`✅ Recurring automation completed: ${result.count} transactions processed`);
      } catch (error) {
        console.error('❌ Recurring automation failed:', error.message);
        logRecurringError(error, { source: 'scheduler' });
      }
    },
    {
      scheduled: true,
      timezone: "Europe/Berlin"
    }
  );
}

// Start scheduler if this file is run directly
if (require.main === module) {
  console.log('🚀 Running recurring payment automation directly...');
  runRecurringAutomation()
    .then(result => {
      console.log(`✅ Complete: ${result.count} transactions processed`);
      console.log(result.logs.join('\n'));
      db.close();
      process.exit(0);
    })
    .catch(error => {
      console.error('❌ Failed:', error.message);
      db.close();
      process.exit(1);
    });
}

