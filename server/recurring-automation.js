/**
 * Recurring Payments Automation Module
 * 
 * Independent backend service that:
 * - Runs on a schedule (daily at 1 AM)
 * - Creates recurring payment transactions automatically
 * - Backfills past due transactions when start date is in the past
 * - Tracks nextDueDate to prevent duplicates
 * - Supports both event-driven and batch processing
 * - Does NOT depend on frontend page loads
 */

const sqlite3 = require('sqlite3').verbose();
const path = require('path');
const fs = require('fs');
const { SOURCE_TAGS } = require('./automation-utils');
const { hasRecurringPaymentChanged } = require('./event-detector');

// Database connection - environment aware
const dbPath = process.env.NODE_ENV === 'test'
  ? path.join(__dirname, '..', 'databases', 'test.db')
  : path.join(__dirname, '..', 'databases', 'production.db');
const db = new sqlite3.Database(dbPath);

// Logs directory
const logsDir = path.join(__dirname, 'logs');
if (!fs.existsSync(logsDir)) {
  fs.mkdirSync(logsDir, { recursive: true });
}

/**
 * Log recurring automation actions with optional source tag
 * @param {string} message - Log message
 * @param {string} [source] - Source tag (e.g., 'event-driven-recurring', 'batch-recurring')
 */
function logRecurringAction(message, source) {
  const timestamp = new Date().toISOString();
  const sourceStr = source ? `[${source}]` : 'RECURRING';
  const logEntry = `${timestamp} | ${sourceStr} | ${message}\n`;
  fs.appendFileSync(path.join(logsDir, 'recurring-automation.log'), logEntry);
}

/**
 * Log recurring automation errors with optional source tag
 * @param {Error} error - Error object
 * @param {object} [details] - Additional details
 * @param {string} [source] - Source tag
 */
function logRecurringError(error, details = {}, source) {
  const timestamp = new Date().toISOString();
  const sourceStr = source ? `[${source}]` : 'RECURRING';
  const logEntry = `${timestamp} | ${sourceStr} | ERROR | ${error.message} | ${JSON.stringify(details)}\n`;
  fs.appendFileSync(path.join(logsDir, 'recurring-automation-errors.log'), logEntry);
}

/**
 * Get all active recurring payments from database
 */
function getActiveRecurringPayments() {
  return new Promise((resolve, reject) => {
    db.all('SELECT * FROM recurring_payments WHERE isActive = 1', [], (err, rows) => {
      if (err) reject(err);
      else resolve(rows);
    });
  });
}

/**
 * Get all transactions from database
 */
function getAllTransactions() {
  return new Promise((resolve, reject) => {
    db.all('SELECT * FROM transactions', [], (err, rows) => {
      if (err) reject(err);
      else resolve(rows);
    });
  });
}

/**
 * Get all categories from database
 */
function getAllCategories() {
  return new Promise((resolve, reject) => {
    db.all('SELECT * FROM categories', [], (err, rows) => {
      if (err) reject(err);
      else resolve(rows);
    });
  });
}

/**
 * Create a transaction in the database
 * @param {object} tx - Transaction data
 * @param {string} [tx.source] - Source tag for tracking
 */
function createTransaction(tx) {
  return new Promise((resolve, reject) => {
    // Always use static query with all columns including user_id
    // Missing values are set to NULL
    const userId = tx.user_id || null;
    
    db.run(
      `INSERT INTO transactions (date, amount, currency, description, type, property_id, category_id, counterparty_id, document_id, isAutoGenerated, source, user_id) 
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [tx.date, tx.amount, tx.currency, tx.description, tx.type,
        tx.property_id, tx.category_id, tx.counterparty_id, tx.document_id, tx.isAutoGenerated, tx.source || null, userId],
      function(err) {
        if (err) reject(err);
        else resolve(this.lastID);
      }
    );
  });
}

/**
 * Update a recurring payment's nextDueDate
 */
function updateRecurringPayment(id, data) {
  return new Promise((resolve, reject) => {
    db.run(
      'UPDATE recurring_payments SET nextDueDate = ? WHERE id = ?',
      [data.nextDueDate, id],
      function(err) {
        if (err) reject(err);
        else resolve();
      }
    );
  });
}

/**
 * Process a single recurring payment and create due transactions
 * @param {object} recurringPayment - Recurring payment data
 * @param {Array} transactions - Existing transactions to check for duplicates
 * @param {Array} categories - Available categories
 * @param {string} [source] - Source tag for tracking (event-driven-recurring, batch-recurring)
 * @param {object} [options] - Additional options
 * @param {string} [options.startDate] - Override start date for processing
 * @param {string} [options.endDate] - Override end date for processing
 * @returns {Promise<Array>} Array of log messages
 */
async function processRecurringPayment(recurringPayment, transactions, categories, source = SOURCE_TAGS.BATCH_RECURRING, options = {}) {
  const today = new Date();
  today.setUTCHours(0, 0, 0, 0);
  const logs = [];

  try {
    // Build a map of category_id to type for fallback
    const categoryTypeMap = {};
    categories.forEach(cat => {
      categoryTypeMap[cat.id] = cat.type;
    });

    // Use startDate for backfill, not nextDueDate
    let current = new Date(recurringPayment.startDate + 'T00:00:00Z');
    
    // Handle invalid start dates
    if (isNaN(current.getTime())) {
      // Fallback: try parsing without timezone
      current = new Date(recurringPayment.startDate);
      if (isNaN(current.getTime())) {
        logRecurringError(new Error(`Invalid start date for recurring payment ${recurringPayment.id}`), { recurringPayment }, source);
        logs.push(`⚠️  Invalid start date for: ${recurringPayment.name}`);
        return logs;
      }
    }

    // Set to start of day in UTC
    current.setUTCHours(0, 0, 0, 0);

    // Determine type: use recurringPayment.type if available, otherwise fallback to category type
    const type = recurringPayment.type || categoryTypeMap[recurringPayment.category_id] || 'EXPENSE';

    while (current <= today) {
      const date = current.toISOString().split('T')[0];
      
      // Check if this transaction already exists (duplicate prevention)
      // Note: Transactions with different sources (event-driven vs batch) are NOT considered duplicates
      // This allows both processing methods to create their own transactions independently
      const alreadyExists = transactions.some(tx =>
        tx.date === date &&
        tx.amount === recurringPayment.amount &&
        tx.description === `Recurring: ${recurringPayment.name}` &&
        (tx.isAutoGenerated === 1 || tx.isAutoGenerated === true) &&
        tx.source === source
      );
      
      if (!alreadyExists) {
        // Extract user_id from recurringPayment for user isolation
        const userId = recurringPayment.user_id || recurringPayment.userId;
        
        const tx = {
          date,
          amount: recurringPayment.amount,
          currency: recurringPayment.currency || 'EUR',
          description: `Recurring: ${recurringPayment.name}`,
          type: type,
          property_id: recurringPayment.property_id || null,
          category_id: recurringPayment.category_id || null,
          counterparty_id: recurringPayment.counterparty_id || null,
          document_id: null,
          isAutoGenerated: 1,
          source: source,
          user_id: userId
        };
        
        try {
          await createTransaction(tx);
          logRecurringAction(`Created recurring transaction: ${recurringPayment.name} (${date})`, source);
          logs.push(`✅ Created: ${recurringPayment.name} (${current.toLocaleDateString()})`);
        } catch (err) {
          logRecurringError(err, { recurringId: recurringPayment.id, date, type: 'create' }, source);
          logs.push(`❌ Failed to create: ${recurringPayment.name} (${current.toLocaleDateString()})`);
        }
      } else {
        logRecurringAction(`Skipped duplicate: ${recurringPayment.name} (${date})`, source);
        logs.push(`⏭️  Skipped duplicate: ${recurringPayment.name} (${current.toLocaleDateString()})`);
      }

      // Increment based on frequency (using UTC methods)
      if (recurringPayment.frequency === 'MONTHLY') {
        current.setUTCMonth(current.getUTCMonth() + 1);
      } else if (recurringPayment.frequency === 'QUARTERLY') {
        current.setUTCMonth(current.getUTCMonth() + 3);
      } else if (recurringPayment.frequency === 'YEARLY') {
        current.setUTCFullYear(current.getUTCFullYear() + 1);
      } else {
        // Default to monthly
        current.setUTCMonth(current.getUTCMonth() + 1);
      }
    }

    // Update nextDueDate to the next occurrence after today
    try {
      await updateRecurringPayment(recurringPayment.id, { nextDueDate: current.toISOString().split('T')[0] });
      logRecurringAction(`Updated nextDueDate for ${recurringPayment.name} to ${current.toISOString().split('T')[0]}`, source);
    } catch (err) {
      logRecurringError(err, { recurringId: recurringPayment.id, type: 'update' }, source);
      logs.push(`⚠️  Failed to update nextDueDate for: ${recurringPayment.name}`);
    }

    return logs;

  } catch (error) {
    logRecurringError(error, { step: 'processRecurringPayment', recurringId: recurringPayment.id }, source);
    return [`❌ Error processing ${recurringPayment.name}: ${error.message}`];
  }
}

