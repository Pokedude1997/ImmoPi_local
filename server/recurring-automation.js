/**
 * Process all recurring payments and create due transactions (for batch processing)
 */
async function processRecurringPayments() {
  const today = new Date();
  today.setUTCHours(0, 0, 0, 0);
  const logs = [];

  try {
    const recurring = await getActiveRecurringPayments();
    const transactions = await getAllTransactions();
    const categories = await getAllCategories();
    
    for (const rp of recurring) {
      const paymentLogs = await processRecurringPayment(
        rp,
        transactions,
        categories,
        SOURCE_TAGS.BATCH_RECURRING
      );
      logs.push(...paymentLogs);
    }

    return logs;

  } catch (error) {
    logRecurringError(error, { step: 'processRecurringPayments' });
    return [`❌ Error: ${error.message}`];
  }
}

/**
 * Main function: Run recurring payment automation
 */
async function runRecurringAutomation() {
  const logs = [];
  const today = new Date();
  today.setUTCHours(0, 0, 0, 0);

  try {
    const paymentLogs = await processRecurringPayments();
    logs.push(...paymentLogs);

    const count = logs.filter(l => l.includes('✅ Created')).length;
    logRecurringAction(`✅ Recurring automation completed: ${count} transactions created`);
    return { success: true, logs, count };

  } catch (error) {
    logRecurringError(error, { step: 'runRecurringAutomation' });
    return { success: false, error: error.message, logs: [] };
  }
}

