/**
 * Handle recurring payment automation for a payment create or update event
 * @param {object} recurringPayment - New/updated recurring payment data (from database)
 * @param {object} [oldRecurringPayment] - Previous recurring payment data (for updates, from database)
 * @param {object} [options] - Additional options
 * @param {string} [options.source] - Override source tag
 * @returns {Promise<object>} Result with success status, logs, and count
 */
async function handleRecurringPaymentEvent(recurringPayment, oldRecurringPayment = null, options = {}) {
  const source = options.source || SOURCE_TAGS.EVENT_DRIVEN_RECURRING;
  const logs = [];
  
  try {
    // For updates: check if recurring payment parameters actually changed
    if (oldRecurringPayment && !hasRecurringPaymentChanged(recurringPayment, oldRecurringPayment)) {
      return { 
        success: true, 
        logs: [`⏭️  Recurring payment unchanged for ${recurringPayment.name} - skipping`], 
        count: 0 
      };
    }
    
    // Get all necessary data from database
    const [transactions, categories] = await Promise.all([
      getAllTransactions(),
      getAllCategories()
    ]);
    
    // Process recurring payment transactions
    const paymentLogs = await processRecurringPayment(
      recurringPayment,
      transactions,
      categories,
      source
    );
    
    logs.push(...paymentLogs);
    
    // Count successful creations
    const createdCount = paymentLogs.filter(log => log.includes('✅ Created')).length;
    
    return { 
      success: true, 
      logs, 
      count: createdCount,
      recurringPaymentId: recurringPayment.id
    };
    
  } catch (error) {
    logRecurringError(error, { recurringPaymentId: recurringPayment.id, source, context: 'handleRecurringPaymentEvent' });
    return { 
      success: false, 
      error: error.message,
      logs: [`❌ Error processing recurring payment ${recurringPayment.name}: ${error.message}`],
      count: 0,
      recurringPaymentId: recurringPayment.id
    };
  }
}

