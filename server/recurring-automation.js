/**
 * Recurring Payments Automation Module
 * 
 * Independent backend service that:
 * - Runs on a schedule (daily at 1 AM)
 * - Creates recurring payment transactions automatically
 * - Backfills past due transactions when start date is in the past
 * - Tracks nextDueDate to prevent duplicates
 * - Does NOT depend on frontend page loads
 */

const sqlite3 = require('sqlite3').verbose();
const path = require('path');
const fs = require('fs');

// Database connection
const dbPath = path.join(__dirname, 'immopi.db');
const db = new sqlite3.Database(dbPath);

// Logs directory
const logsDir = path.join(__dirname, 'logs');
if (!fs.existsSync(logsDir)) {
  fs.mkdirSync(logsDir, { recursive: true });
}

/**
 * Log recurring automation actions with optional source tag
 * @param {string} message - Log message
 * @param {string} [source] - Source tag (e.g., 'event-driven-recurring', 'batch-recurring')
 */
function logRecurringAction(message, source) {
  const timestamp = new Date().toISOString();
  const sourceStr = source ? `[${source}]` : 'RECURRING';
  const logEntry = `${timestamp} | ${sourceStr} | ${message}\n`;
  fs.appendFileSync(path.join(logsDir, 'recurring-automation.log'), logEntry);
}

/**
 * Log recurring automation errors with optional source tag
 * @param {Error} error - Error object
 * @param {object} [details] - Additional details
 * @param {string} [source] - Source tag
 */
function logRecurringError(error, details = {}, source) {
  const timestamp = new Date().toISOString();
  const sourceStr = source ? `[${source}]` : 'RECURRING';
  const logEntry = `${timestamp} | ${sourceStr} | ERROR | ${error.message} | ${JSON.stringify(details)}\n`;
  fs.appendFileSync(path.join(logsDir, 'recurring-automation-errors.log'), logEntry);
}

/**
 * Get all active recurring payments from database
 */
function getActiveRecurringPayments() {
  return new Promise((resolve, reject) => {
    db.all('SELECT * FROM recurring_payments WHERE isActive = 1', [], (err, rows) => {
      if (err) reject(err);
      else resolve(rows);
    });
  });
}

/**
 * Get all transactions from database
 */
function getAllTransactions() {
  return new Promise((resolve, reject) => {
    db.all('SELECT * FROM transactions', [], (err, rows) => {
      if (err) reject(err);
      else resolve(rows);
    });
  });
}

/**
 * Get all categories from database
 */
function getAllCategories() {
  return new Promise((resolve, reject) => {
    db.all('SELECT * FROM categories', [], (err, rows) => {
      if (err) reject(err);
      else resolve(rows);
    });
  });
}

/**
 * Create a transaction in the database
 */
function createTransaction(tx) {
  return new Promise((resolve, reject) => {
    db.run(
      `INSERT INTO transactions (date, amount, currency, description, type, property_id, category_id, counterparty_id, document_id, isAutoGenerated) 
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [tx.date, tx.amount, tx.currency, tx.description, tx.type,
       tx.property_id, tx.category_id, tx.counterparty_id, tx.document_id, tx.isAutoGenerated],
      function(err) {
        if (err) reject(err);
        else resolve(this.lastID);
      }
    );
  });
}

/**
 * Update a recurring payment's nextDueDate
 */
function updateRecurringPayment(id, data) {
  return new Promise((resolve, reject) => {
    db.run(
      'UPDATE recurring_payments SET nextDueDate = ? WHERE id = ?',
      [data.nextDueDate, id],
      function(err) {
        if (err) reject(err);
        else resolve();
      }
    );
  });
}

/**
 * Process all recurring payments and create due transactions
 */
async function processRecurringPayments() {
  const today = new Date();
  today.setUTCHours(0, 0, 0, 0);
  const logs = [];

  try {
    const recurring = await getActiveRecurringPayments();
    const transactions = await getAllTransactions();
    const categories = await getAllCategories();
    
    // Build a map of category_id to type for fallback
    const categoryTypeMap = {};
    categories.forEach(cat => {
      categoryTypeMap[cat.id] = cat.type;
    });

    for (const rp of recurring) {
      // Use startDate for backfill, not nextDueDate
      let current = new Date(rp.startDate + 'T00:00:00Z');
      
      // Handle invalid start dates
      if (isNaN(current.getTime())) {
        // Fallback: try parsing without timezone
        current = new Date(rp.startDate);
        if (isNaN(current.getTime())) {
          logRecurringError(new Error(`Invalid start date for recurring payment ${rp.id}`), { rp });
          logs.push(`⚠️  Invalid start date for: ${rp.name}`);
          continue;
        }
      }

      // Set to start of day in UTC
      current.setUTCHours(0, 0, 0, 0);

      // Determine type: use rp.type if available, otherwise fallback to category type
      const type = rp.type || categoryTypeMap[rp.category_id] || 'EXPENSE';

      while (current <= today) {
        const date = current.toISOString().split('T')[0];
        
        // Check if this transaction already exists (duplicate prevention)
        const alreadyExists = transactions.some(tx =>
          tx.date === date &&
          tx.amount === rp.amount &&
          tx.description === `Recurring: ${rp.name}` &&
          (tx.isAutoGenerated === 1 || tx.isAutoGenerated === true)
        );
        
        if (!alreadyExists) {
          const tx = {
            date,
            amount: rp.amount,
            currency: rp.currency || 'EUR',
            description: `Recurring: ${rp.name}`,
            type: type,
            property_id: rp.property_id || null,
            category_id: rp.category_id || null,
            counterparty_id: rp.counterparty_id || null,
            document_id: null,
            isAutoGenerated: 1
          };
          
          try {
            await createTransaction(tx);
            logRecurringAction(`Created recurring transaction: ${rp.name} (${date})`);
            logs.push(`✅ Created: ${rp.name} (${current.toLocaleDateString()})`);
          } catch (err) {
            logRecurringError(err, { recurringId: rp.id, date, type: 'create' });
            logs.push(`❌ Failed to create: ${rp.name} (${current.toLocaleDateString()})`);
          }
        } else {
          logRecurringAction(`Skipped duplicate: ${rp.name} (${date})`);
          logs.push(`⏭️  Skipped duplicate: ${rp.name} (${current.toLocaleDateString()})`);
        }

        // Increment based on frequency (using UTC methods)
        if (rp.frequency === 'MONTHLY') {
          current.setUTCMonth(current.getUTCMonth() + 1);
        } else if (rp.frequency === 'QUARTERLY') {
          current.setUTCMonth(current.getUTCMonth() + 3);
        } else if (rp.frequency === 'YEARLY') {
          current.setUTCFullYear(current.getUTCFullYear() + 1);
        } else {
          // Default to monthly
          current.setUTCMonth(current.getUTCMonth() + 1);
        }
      }

      // Update nextDueDate to the next occurrence after today
      try {
        await updateRecurringPayment(rp.id, { nextDueDate: current.toISOString().split('T')[0] });
        logRecurringAction(`Updated nextDueDate for ${rp.name} to ${current.toISOString().split('T')[0]}`);
      } catch (err) {
        logRecurringError(err, { recurringId: rp.id, type: 'update' });
        logs.push(`⚠️  Failed to update nextDueDate for: ${rp.name}`);
      }
    }

    return logs;

  } catch (error) {
    logRecurringError(error, { step: 'processRecurringPayments' });
    return [`❌ Error: ${error.message}`];
  }
}

/**
 * Main function: Run recurring payment automation
 */
async function runRecurringAutomation() {
  const logs = [];
  const today = new Date();
  today.setUTCHours(0, 0, 0, 0);

  try {
    const paymentLogs = await processRecurringPayments();
    logs.push(...paymentLogs);

    const count = logs.filter(l => l.includes('✅ Created')).length;
    logRecurringAction(`✅ Recurring automation completed: ${count} transactions created`);
    return { success: true, logs, count };

  } catch (error) {
    logRecurringError(error, { step: 'runRecurringAutomation' });
    return { success: false, error: error.message, logs: [] };
  }
}

// ============================================================================
// SCHEDULER
// ============================================================================

let recurringSchedulerInitialized = false;

function startRecurringScheduler() {
  if (recurringSchedulerInitialized) return;
  recurringSchedulerInitialized = true;

  const cron = require('node-cron');

  console.log('📅 Recurring automation scheduler starting...');
  console.log('⏰ Schedule: Every day at 1:00 AM (Europe/Berlin timezone)');

  // Run daily at 1 AM
  cron.schedule(
    '0 1 * * *',
    async () => {
      console.log('\n🔄 Running recurring payment automation...');
      try {
        const result = await runRecurringAutomation();
        console.log(`✅ Recurring automation completed: ${result.count} transactions processed`);
      } catch (error) {
        console.error('❌ Recurring automation failed:', error.message);
        logRecurringError(error, { source: 'scheduler' });
      }
    },
    {
      scheduled: true,
      timezone: "Europe/Berlin"
    }
  );
}

// Start scheduler if this file is run directly
if (require.main === module) {
  console.log('🚀 Running recurring payment automation directly...');
  runRecurringAutomation()
    .then(result => {
      console.log(`✅ Complete: ${result.count} transactions processed`);
      console.log(result.logs.join('\n'));
      db.close();
      process.exit(0);
    })
    .catch(error => {
      console.error('❌ Failed:', error.message);
      db.close();
      process.exit(1);
    });
}

module.exports = {
  runRecurringAutomation,
  startRecurringScheduler
};
