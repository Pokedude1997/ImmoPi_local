const assert = require('assert');
const {
  createTestDatabase,
  initializeTestSchema,
  createTestProperty,
  createTestTenant,
  createTestCategory,
  createTestTenantContract,
  createTestRecurringPayment,
  getAllRecords,
  clearAllTestData,
  cleanupTestDatabase
} = require('./setup');

const { hasMortgageChanged, hasMortgageData, hasPaymentTermsChanged, hasRecurringPaymentChanged, shouldTriggerAutomation } = require('../event-detector');
const { SOURCE_TAGS, getSourceTag, isAutoGeneratedTransaction } = require('../automation-utils');

// Test suite for Phase 1 utilities
describe('Phase 1: Event Detector', () => {
  beforeEach(async () => {
    await createTestDatabase();
    await initializeTestSchema();
  });

  afterEach(async () => {
    await clearAllTestData();
  });

  after(async () => {
    await cleanupTestDatabase();
  });

  describe('hasMortgageData()', () => {
    it('should return true for property with mortgage data', () => {
      const property = {
        mortgage_loanAmount: 200000,
        mortgage_startDate: '2025-01-01',
        mortgage_interestRate: 3.5,
        mortgage_principalRate: 2.0
      };
      assert.strictEqual(hasMortgageData(property), true);
    });

    it('should return false for property without mortgage data', () => {
      const property = {
        name: 'Test Property',
        purchasePrice: 300000
      };
      assert.strictEqual(hasMortgageData(property), false);
    });

    it('should return false for null property', () => {
      assert.strictEqual(hasMortgageData(null), false);
    });
  });

  describe('hasMortgageChanged()', () => {
    it('should return true when creating new property with mortgage', () => {
      const newProperty = {
        mortgage_loanAmount: 200000,
        mortgage_startDate: '2025-01-01'
      };
      assert.strictEqual(hasMortgageChanged(newProperty, null), true);
    });

    it('should return true when mortgage amount changes', () => {
      const oldProperty = { mortgage_loanAmount: 200000 };
      const newProperty = { mortgage_loanAmount: 250000 };
      assert.strictEqual(hasMortgageChanged(newProperty, oldProperty), true);
    });

    it('should return false when mortgage data is unchanged', () => {
      const property = {
        mortgage_loanAmount: 200000,
        mortgage_startDate: '2025-01-01'
      };
      assert.strictEqual(hasMortgageChanged(property, property), false);
    });
  });

  describe('hasPaymentTermsChanged()', () => {
    it('should return true when creating new contract', () => {
      const newContract = { coldRent: 1000, sideCosts: 200 };
      assert.strictEqual(hasPaymentTermsChanged(newContract, null), true);
    });

    it('should return true when cold rent changes', () => {
      const oldContract = { coldRent: 1000, sideCosts: 200 };
      const newContract = { coldRent: 1200, sideCosts: 200 };
      assert.strictEqual(hasPaymentTermsChanged(newContract, oldContract), true);
    });

    it('should return false when payment terms are unchanged', () => {
      const contract = { coldRent: 1000, sideCosts: 200 };
      assert.strictEqual(hasPaymentTermsChanged(contract, contract), false);
    });
  });

  describe('hasRecurringPaymentChanged()', () => {
    it('should return true when creating new recurring payment', () => {
      const newRecurring = { amount: 500, frequency: 'monthly' };
      assert.strictEqual(hasRecurringPaymentChanged(newRecurring, null), true);
    });

    it('should return true when amount changes', () => {
      const oldRecurring = { amount: 500, frequency: 'monthly' };
      const newRecurring = { amount: 600, frequency: 'monthly' };
      assert.strictEqual(hasRecurringPaymentChanged(newRecurring, oldRecurring), true);
    });

    it('should return false when recurring payment is unchanged', () => {
      const recurring = { amount: 500, frequency: 'monthly' };
      assert.strictEqual(hasRecurringPaymentChanged(recurring, recurring), false);
    });
  });

  describe('shouldTriggerAutomation()', () => {
    it('should trigger mortgage automation for new property with mortgage', () => {
      const newProperty = { mortgage_loanAmount: 200000 };
      const result = shouldTriggerAutomation('property', newProperty, null);
      assert.strictEqual(result.trigger, true);
      assert.strictEqual(result.changeType, 'create');
    });

    it('should not trigger mortgage automation for property without mortgage', () => {
      const newProperty = { name: 'Test' };
      const result = shouldTriggerAutomation('property', newProperty, null);
      assert.strictEqual(result.trigger, false);
    });

    it('should trigger mortgage automation when mortgage changes', () => {
      const oldProperty = { mortgage_loanAmount: 200000 };
      const newProperty = { mortgage_loanAmount: 250000 };
      const result = shouldTriggerAutomation('property', newProperty, oldProperty);
      assert.strictEqual(result.trigger, true);
      assert.strictEqual(result.changeType, 'update');
    });
  });
});

// Test suite for Automation Utils
describe('Phase 1: Automation Utils', () => {
  describe('SOURCE_TAGS', () => {
    it('should have all required source tags', () => {
      assert.ok(SOURCE_TAGS.EVENT_DRIVEN_MORTGAGE);
      assert.ok(SOURCE_TAGS.EVENT_DRIVEN_RECURRING);
      assert.ok(SOURCE_TAGS.EVENT_DRIVEN_RENT);
      assert.ok(SOURCE_TAGS.BATCH_MORTGAGE);
      assert.ok(SOURCE_TAGS.BATCH_RECURRING);
      assert.ok(SOURCE_TAGS.BATCH_RENT);
      assert.ok(SOURCE_TAGS.MANUAL);
    });
  });

  describe('getSourceTag()', () => {
    it('should return event-driven tag for mortgage when isEventDriven is true', () => {
      const tag = getSourceTag('mortgage', true);
      assert.strictEqual(tag, SOURCE_TAGS.EVENT_DRIVEN_MORTGAGE);
    });

    it('should return batch tag for mortgage when isEventDriven is false', () => {
      const tag = getSourceTag('mortgage', false);
      assert.strictEqual(tag, SOURCE_TAGS.BATCH_MORTGAGE);
    });

    it('should return event-driven tag for rent', () => {
      const tag = getSourceTag('rent', true);
      assert.strictEqual(tag, SOURCE_TAGS.EVENT_DRIVEN_RENT);
    });

    it('should return event-driven tag for recurring', () => {
      const tag = getSourceTag('recurring', true);
      assert.strictEqual(tag, SOURCE_TAGS.EVENT_DRIVEN_RECURRING);
    });
  });

  describe('isAutoGeneratedTransaction()', () => {
    it('should return true for mortgage payment description', () => {
      assert.strictEqual(isAutoGeneratedTransaction('Mortgage Payment: Property 1 - Jan 2025'), true);
    });

    it('should return true for rent payment description', () => {
      assert.strictEqual(isAutoGeneratedTransaction('Rent Payment: Property A - Jan 2025'), true);
    });

    it('should return false for manual description', () => {
      assert.strictEqual(isAutoGeneratedTransaction('Manual payment from tenant'), false);
    });

    it('should return false for null description', () => {
      assert.strictEqual(isAutoGeneratedTransaction(null), false);
    });
  });
});

