/**
 * Mortgage Automation Module
 * 
 * Independent backend service that:
 * - Runs on a schedule (daily at 2 AM)
 * - Creates mortgage interest/principal transactions automatically
 * - Tracks last execution to prevent duplicates
 * - Does NOT depend on frontend page loads
 */

const sqlite3 = require('sqlite3').verbose();
const path = require('path');
const fs = require('fs');

// Database connection
const dbPath = path.join(__dirname, 'immopi.db');
const db = new sqlite3.Database(dbPath);

// Logs directory
const logsDir = path.join(__dirname, 'logs');
if (!fs.existsSync(logsDir)) {
  fs.mkdirSync(logsDir, { recursive: true });
}

function logMortgageAction(message) {
  const timestamp = new Date().toISOString();
  const logEntry = `${timestamp} | ${message}\n`;
  fs.appendFileSync(path.join(logsDir, 'mortgage-automation.log'), logEntry);
}

function logMortgageError(error, details = {}) {
  const timestamp = new Date().toISOString();
  const logEntry = `${timestamp} | ERROR | ${error.message} | ${JSON.stringify(details)}\n`;
  fs.appendFileSync(path.join(logsDir, 'mortgage-automation-errors.log'), logEntry);
}

/**
 * Find category by name from the categories array
 */
function findCategoryByName(categories, name) {
  return categories.find(c => c.name === name);
}

/**
 * Process mortgage transactions for a single property
 */
function processMortgageTransactions(property, currentYear, transactions, categories) {
  const logs = [];
  const mortgage = property.mortgage;
  
  if (!mortgage || !mortgage.startDate) {
    return logs;
  }

  const today = new Date();
  today.setHours(0, 0, 0, 0);

  const startDate = new Date(mortgage.startDate);
  if (isNaN(startDate.getTime())) {
    logMortgageError(new Error(`Invalid start date for property ${property.id}`), { property, mortgage });
    return logs;
  }

  // Find category IDs for mortgage interest and principal
  const mortgageInterestCategory = findCategoryByName(categories, 'Mortgage Interest');
  const mortgagePrincipalCategory = findCategoryByName(categories, 'Mortgage Principal');
  
  // Fallback to first EXPENSE category if mortgage categories don't exist
  const defaultExpenseCategory = categories.find(c => c.type === 'EXPENSE');
  const interestCategoryId = mortgageInterestCategory?.id || defaultExpenseCategory?.id;
  const principalCategoryId = mortgagePrincipalCategory?.id || defaultExpenseCategory?.id;
  
  if (!interestCategoryId || !principalCategoryId) {
    logMortgageError(new Error(`No mortgage categories found for property ${property.id}`), { property });
    logs.push(`⚠️  No mortgage categories found for property ${property.name}`);
    return logs;
  }

  // Calculate monthly payment components
  const annualInterestRate = mortgage.interestRate / 100;
  const annualPrincipalRate = mortgage.principalRate / 100;
  const monthlyInterestAmount = (mortgage.loanAmount * annualInterestRate) / 12;
  const monthlyPrincipalAmount = (mortgage.loanAmount * annualPrincipalRate) / 12;
  
  const current = new Date(startDate.getFullYear(), startDate.getMonth(), 1);
  const yearEnd = new Date(currentYear, 11, 31);

  while (current <= yearEnd) {
    const paymentDate = mortgage.paymentTiming === 'END_OF_MONTH'
      ? new Date(current.getFullYear(), current.getMonth() + 1, 0)
      : new Date(current.getFullYear(), current.getMonth(), 1);

    if (paymentDate.getFullYear() === currentYear && paymentDate <= today) {
      const date = paymentDate.toISOString().split('T')[0];
      const paymentMonth = paymentDate.getMonth();
      const paymentYear = paymentDate.getFullYear();
      
      // Check if mortgage transactions already exist for THIS property and THIS MONTH
      // Uses property name in description to catch both old and new transactions
      const mortgageTransactionsThisMonth = transactions.filter(tx =>
        (tx.isAutoGenerated === 1 || tx.isAutoGenerated === true) &&
        (tx.description?.includes('Mortgage interest') || tx.description?.includes('Mortgage principal')) &&
        tx.description?.includes(property.name) &&
        new Date(tx.date).getFullYear() === paymentYear &&
        new Date(tx.date).getMonth() === paymentMonth
      );
      
      const hasInterestThisMonth = mortgageTransactionsThisMonth.some(tx => 
        tx.description?.includes('Mortgage interest')
      );
      const hasPrincipalThisMonth = mortgageTransactionsThisMonth.some(tx => 
        tx.description?.includes('Mortgage principal')
      );

      if (!hasInterestThisMonth) {
        const interestTx = {
          date,
          amount: Number(monthlyInterestAmount.toFixed(2)),
          currency: 'EUR',
          description: `Mortgage interest for ${property.name}`,
          type: 'EXPENSE',
          property_id: property.id,
          category_id: interestCategoryId,
          counterparty_id: null,
          document_id: null,
          isAutoGenerated: 1,
        };
        
        createTransaction(interestTx)
          .then(() => {
            logMortgageAction(`Mortgage interest created for ${property.name} on ${date}`);
            logs.push(`Mortgage interest created for ${property.name} on ${date}`);
          })
          .catch(err => {
            logMortgageError(err, { propertyId: property.id, type: 'interest' });
            logs.push(`❌ Failed to create mortgage interest for ${property.name}`);
          });
      }
      
      if (!hasPrincipalThisMonth) {
        const principalTx = {
          date,
          amount: Number(monthlyPrincipalAmount.toFixed(2)),
          currency: 'EUR',
          description: `Mortgage principal for ${property.name}`,
          type: 'EXPENSE',
          property_id: property.id,
          category_id: principalCategoryId,
          counterparty_id: null,
          document_id: null,
          isAutoGenerated: 1,
        };
        
        createTransaction(principalTx)
          .then(() => {
            logMortgageAction(`Mortgage principal created for ${property.name} on ${date}`);
            logs.push(`Mortgage principal created for ${property.name} on ${date}`);
          })
          .catch(err => {
            logMortgageError(err, { propertyId: property.id, type: 'principal' });
            logs.push(`❌ Failed to create mortgage principal for ${property.name}`);
          });
      }
    }
    
    current.setMonth(current.getMonth() + 1);
  }
  
  return logs;
}

/**
 * Create a transaction in the database
 */
function createTransaction(tx) {
  return new Promise((resolve, reject) => {
    db.run(
      `INSERT INTO transactions (date, amount, currency, description, type, property_id, category_id, counterparty_id, document_id, isAutoGenerated) 
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [tx.date, tx.amount, tx.currency, tx.description, tx.type, 
       tx.property_id, tx.category_id, tx.counterparty_id, tx.document_id, tx.isAutoGenerated],
      function(err) {
        if (err) reject(err);
        else resolve(this.lastID);
      }
    );
  });
}

/**
 * Check if automation already ran for this month
 */
function checkAlreadyRanThisMonth() {
  return new Promise((resolve, reject) => {
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const currentMonthKey = `${today.getFullYear()}-${today.getMonth()}`;
    
    db.get('SELECT lastMortgageRun FROM automation_state WHERE id = 1', [], (err, row) => {
      if (err) return reject(err);
      resolve(row ? row.lastMortgageRun === currentMonthKey : false);
    });
  });
}

/**
 * Update last automation run date
 */
function updateLastRun() {
  return new Promise((resolve, reject) => {
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const currentMonthKey = `${today.getFullYear()}-${today.getMonth()}`;
    
    db.run(
      'UPDATE automation_state SET lastMortgageRun = ? WHERE id = 1',
      [currentMonthKey],
      function(err) {
        if (err) reject(err);
        else resolve();
      }
    );
  });
}

/**
 * Main function: Run mortgage automation for all properties
 */
async function runMortgageAutomation() {
  const logs = [];
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const currentYear = today.getFullYear();
  
  try {
    // Check if already ran this month
    const alreadyRan = await checkAlreadyRanThisMonth();
    if (alreadyRan) {
      logMortgageAction('⏭️  Mortgage automation already ran for this month');
      return { success: true, logs: ['⏭️  Mortgage automation already ran for this month'], count: 0 };
    }
    
    // Get all data from database
    const properties = await new Promise((resolve, reject) => {
      db.all('SELECT * FROM properties', [], (err, rows) => {
        if (err) reject(err);
        else resolve(rows);
      });
    });
    
    const transactions = await new Promise((resolve, reject) => {
      db.all('SELECT * FROM transactions', [], (err, rows) => {
        if (err) reject(err);
        else resolve(rows);
      });
    });
    
    const categories = await new Promise((resolve, reject) => {
      db.all('SELECT * FROM categories', [], (err, rows) => {
        if (err) reject(err);
        else resolve(rows);
      });
    });
    
    // Process each property with mortgage
    for (const property of properties) {
      // Transform mortgage data from flat columns to object
      const mortgageData = property.mortgage_loanAmount !== null ? {
        loanAmount: property.mortgage_loanAmount,
        startDate: property.mortgage_startDate,
        interestRate: property.mortgage_interestRate,
        principalRate: property.mortgage_principalRate,
        bankName: property.mortgage_bankName,
        paymentTiming: property.mortgage_paymentTiming,
      } : null;
      
      const propWithMortgage = {
        ...property,
        id: String(property.id),
        mortgage: mortgageData,
      };
      
      const mortgageLogs = processMortgageTransactions(
        propWithMortgage,
        currentYear,
        transactions,
        categories
      );
      logs.push(...mortgageLogs);
    }
    
    // Update last run date
    await updateLastRun();
    
    logMortgageAction(`✅ Mortgage automation completed: ${logs.length} transactions processed`);
    return { success: true, logs, count: logs.length };
    
  } catch (error) {
    logMortgageError(error, { step: 'runMortgageAutomation' });
    return { success: false, error: error.message, logs: [] };
  }
}

// ============================================================================
// SCHEDULER
// ============================================================================

let mortgageSchedulerInitialized = false;

function startMortgageScheduler() {
  if (mortgageSchedulerInitialized) return;
  mortgageSchedulerInitialized = true;

  const cron = require('node-cron');

  console.log('📅 Mortgage automation scheduler starting...');
  console.log('⏰ Schedule: Every day at 2:00 AM (Europe/Berlin timezone)');

  // Run daily at 2 AM
  cron.schedule(
    '0 2 * * *', 
    async () => {
      console.log('\n🔄 Running mortgage automation...');
      try {
        const result = await runMortgageAutomation();
        console.log(`✅ Mortgage automation completed: ${result.logs.length} transactions processed`);
      } catch (error) {
        console.error('❌ Mortgage automation failed:', error.message);
        logMortgageError(error, { source: 'scheduler' });
      }
    },
    {
      scheduled: true,
      timezone: "Europe/Berlin"
    }
  );
}

// Start scheduler if this file is run directly
if (require.main === module) {
  console.log('🚀 Running mortgage automation directly...');
  runMortgageAutomation()
    .then(result => {
      console.log(`✅ Complete: ${result.logs.length} transactions processed`);
      console.log(result.logs.join('\n'));
      db.close();
      process.exit(0);
    })
    .catch(error => {
      console.error('❌ Failed:', error.message);
      db.close();
      process.exit(1);
    });
}

module.exports = { 
  runMortgageAutomation, 
  startMortgageScheduler 
};
